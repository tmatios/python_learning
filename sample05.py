
### 4: Python基本文法を学ぶ初心者向けサンプルコード集

#### 4-1: Python初心者が挫折しないためのプログラミング入門


# 基本的な計算
a = 10
b = 5
print(f"{a} + {b} = {a + b}")
print(f"{a} - {b} = {a - b}")
print(f"{a} * {b} = {a * b}")
print(f"{a} / {b} = {a / b}")

# if文の例
number = 7
if number % 2 == 0:
    print(f"{number}は偶数です")
else:
    print(f"{number}は奇数です")
